"""Versioned baked scientific artifacts and bounded certificate replay.

The Geometric Function Atlas website publishes immutable scientific artifacts:
Schur-parameter coefficient expansions, a coefficient-bound catalog, machine
proof certificates, open-problem brackets and conjectures, literature
reconciliation rows, and a method reference document. This module exposes those
artifacts through the standalone package as a versioned, checksummed, read-only
snapshot (``src/geometric_function_atlas/data/``), regenerated by
``scripts/bake_artifacts.py`` from the website repository.

Evidence boundaries (the website's honesty model, preserved here):

* Exact expansion and bound strings are exact *transcriptions* of the published
  snapshot; sharpness, enclosure, attainment, and provenance are carried by the
  record fields and are never inferred by this package.
* ``verify_certificate`` replays the certificate's declared extremal through the
  package's exact Schur machinery. A passing replay certifies that the stored
  extremal attains the stored candidate under the declared class assumptions; it
  is not a new proof and not peer review.
* Every lookup is fail-closed: unknown keys, missing artifacts, checksum or
  schema mismatches, unsupported functionals, and resource exhaustion raise
  explicit errors; nothing is guessed.

All payloads are deterministic JSON under the closed ``snapshot`` result
envelope documented in ``docs/RESULT_CONTRACT.md``.
"""

