# ── bounded certificate replay ────────────────────────────────────────────────


def verify_certificate(name: str) -> dict[str, Any]:
    """Replay one certificate's declared extremal through the exact Schur machinery.

    The replay recomputes the coefficient functional at the certificate's
    stored extremal Schur parameters using the class phi coefficients from the
    versioned snapshot, then compares the exact value with the certificate's
    declared candidate. Fail-closed outcomes:

    * unknown certificate or unsupported functional -> ``UnsupportedError``;
    * extremal not exactly representable or absent -> ``UnresolvedError``;
    * resource bounds (Schur depth / coefficient order) -> ``ResourceLimitError``;
    * recomputed value inconsistent with the declared candidate or upper bound
      -> ``CorruptArtifactError``.

    A passing replay certifies extremal attainment of the stored candidate
    under the declared class assumptions; it is not a new proof and not peer
    review, and it does not depend on the stripped leaf archive.
    """
    certificates = _certificates()
    try:
        certificate = certificates[name]
    except KeyError as exc:
        raise UnsupportedError(
            f"unknown certificate {name!r}; use 'gfa proofs' to list names"
        ) from exc
    class_key = certificate["class"]
    functional_key = certificate["functional"]
    class_record = _require_class(class_key)
    sharp = certificate.get("sharp") or {}
    candidate = sharp.get("candidate") or {}
    gammas = sharp.get("extremal_gammas") or []
    if not gammas:
        raise UnresolvedError(
            f"certificate {name} carries no extremal gammas for replay"
        )
    normalized = [_normalize_gamma(value) for value in gammas]
    phi_coeffs = list(class_record["phi_coeffs"])
    coefficients = member_coefficients(
        phi_coeffs, normalized, order=MAX_REPLAY_ORDER
    )
    value = functional_value(functional_key, coefficients)
    value_float = float(sp.N(value, 30))

    bound = _exact_or_float(certificate, "bound")
    if bound is None:
        raise CorruptArtifactError(
            f"certificate {name} carries no bound value for replay"
        )
    bound_float = float(sp.N(bound, 30)) if isinstance(bound, sp.Expr) else float(bound)
    slack = certificate.get("slack")
    tolerance = float(slack) if isinstance(slack, (int, float)) else 1e-9

    expected_exact = candidate.get("value_exact")
    expected_float = candidate.get("value_float")

    checks: list[VerificationCheck] = []
    if expected_exact is not None:
        try:
            parsed = parse_exact_expression(str(expected_exact))
        except ExactExpressionError as exc:
            raise CorruptArtifactError(
                f"certificate {name} candidate value_exact is not a valid "
                "exact expression"
            ) from exc
        attained = sp.simplify(value - parsed) == 0
        expected = str(expected_exact)
    elif expected_float is not None:
        attained = abs(value_float - float(expected_float)) <= tolerance
        expected = f"{expected_float} ± {tolerance}"
    else:
        raise UnresolvedError(
            f"certificate {name} declares no candidate value for replay"
        )
    checks.append(
        VerificationCheck(
            name="extremal_attainment",
            checked="functional value at the stored extremal Schur parameters",
            expected=expected,
            observed=str(value),
            status=CheckStatus.PASS if attained else CheckStatus.FAIL,
            scope="certificate replay (exact Schur machinery)",
            failure_reason=None if attained else "recomputed value differs",
        )
    )

    bound_consistent = value_float <= bound_float + tolerance
    checks.append(
        VerificationCheck(
            name="upper_bound_consistency",
            checked="replayed value lies within the certified upper bound + slack",
            expected=f"{bound_float} + {tolerance}",
            observed=value_float,
            status=CheckStatus.PASS if bound_consistent else CheckStatus.FAIL,
            scope="certificate replay (exact Schur machinery)",
            failure_reason=None
            if bound_consistent
            else "replayed value exceeds the declared bound",
        )
    )
    report = VerificationReport(tuple(checks))
    if not report.success:
        failed = [check for check in checks if check.status is CheckStatus.FAIL]
        detail = "; ".join(f"{check.name}: {check.failure_reason}" for check in failed)
        raise CorruptArtifactError(
            f"certificate {name} failed replay: {detail}"
        )
    return {
        "name": name,
        "class_key": class_key,
        "functional_key": functional_key,
        "functional_value_exact": str(value),
        "functional_value_float": value_float,
        "candidate_exact": expected_exact,
        "candidate_float": expected_float,
        "bound": certificate.get("bound"),
        "bound_float": bound_float,
        "slack": slack,
        "sharp": bool(sharp.get("proven")),
        "matched": True,
    }


# ── closed snapshot result envelope ───────────────────────────────────────────


def _count_dag(count: int) -> dict[str, Any]:
    """Minimal canonical DAG encoding an exact record count."""
    return canonical_expression_dag({"count": sp.Integer(count)})


def _parse_exact_expression_map(
    expressions: Mapping[str, Any],
) -> tuple[dict[str, Any], dict[str, Any]]:
    """Split named values into (exact-expressions, sympy DAG sources).

    Strings are parsed with the restricted eval-free parser; values that do not
    parse are omitted from the DAG (the checksummed record stays authoritative).
    """
    exact: dict[str, Any] = {}
    dag_sources: dict[str, Any] = {}
    for name, value in expressions.items():
        if isinstance(value, (list, tuple)):
            parsed: list[sp.Expr] = []
            for item in value:
                try:
                    parsed.append(parse_exact_expression(str(item)))
                except ExactExpressionError:
                    parsed = []
                    break
            if parsed:
                exact[name] = [str(item) for item in value]
                dag_sources[name] = parsed
        else:
            try:
                expr = parse_exact_expression(str(value))
            except ExactExpressionError:
                continue
            exact[name] = str(value)
            dag_sources[name] = expr
    return exact, dag_sources


def snapshot_payload(
    *,
    result_type: str,
    canonical_inputs: Mapping[str, Any],
    record: Mapping[str, Any],
    evidence_status: str,
    assumptions: tuple[str, ...] | list[str],
    source_references: tuple[str, ...] | list[str],
    verification: VerificationReport,
    exact_expressions: Mapping[str, Any] | None = None,
    record_count: int | None = None,
) -> dict[str, Any]:
    """Assemble the closed snapshot result envelope for one operation."""
    if result_type not in _SNAPSHOT_RESULT_TYPES:
        raise ValueError(f"unsupported snapshot result_type: {result_type!r}")
    manifest = _manifest()
    if exact_expressions:
        exact, dag_sources = _parse_exact_expression_map(exact_expressions)
        if dag_sources:
            dag = canonical_expression_dag(dag_sources)
        elif record_count is not None:
            exact = {}
            dag = _count_dag(record_count)
        else:
            dag = canonical_expression_dag(
                {"count": sp.Integer(len(json.dumps(record, sort_keys=True)))}
            )
    else:
        exact = {}
        count = record_count
        if count is None:
            count = len(record) if isinstance(record, Mapping) else 0
        dag = _count_dag(count)
    payload: dict[str, Any] = {
        "schema_version": SNAPSHOT_SCHEMA_VERSION,
        "result_type": result_type,
        "canonical_inputs": dict(canonical_inputs),
        "exact_expressions": exact,
        "exact_expression_dag": dag,
        "method": _LOOKUP_METHODS[result_type],
        "evidence_status": evidence_status,
        "computational_status": evidence_status,
        "assumptions": list(assumptions),
        "source_references": list(source_references),
        "package_version": __version__,
        "artifact_versions": {
            "generator_catalog": f"gfa_classes:{manifest['artifact_version']}",
            "source_commit": manifest["source_commit"],
            "fixture_or_proof": f"gfa_artifacts:{manifest['artifact_version']}",
            "snapshot_date": manifest["snapshot_date"],
            "snapshot_schema": str(SNAPSHOT_SCHEMA_VERSION),
        },
        "literature_status": LiteratureStatus.NOT_ASSESSED.value,
        "novelty_claim": False,
        "failure_state": None,
        "verification": verification.to_dict(),
        "provenance": "built_in",
        "record": dict(record),
    }
    json.dumps(payload, allow_nan=False)
    validate_snapshot_payload(payload)
    return payload


def validate_snapshot_payload(payload: Mapping[str, Any]) -> None:
    """Validate a snapshot result against the closed envelope.

    This dependency-free validator mirrors ``validate_error_payload``: it
    rejects unknown top-level keys, requires the exact envelope, and enforces
    the fail-closed status coherence rules. The JSON schema shipped at
    ``schema/result.schema.json`` accepts the same payloads.
    """
    envelope = {
        "schema_version",
        "result_type",
        "canonical_inputs",
        "exact_expressions",
        "exact_expression_dag",
        "method",
        "evidence_status",
        "computational_status",
        "assumptions",
        "source_references",
        "package_version",
        "artifact_versions",
        "literature_status",
        "novelty_claim",
        "failure_state",
        "verification",
        "provenance",
        "record",
    }
    if not isinstance(payload, Mapping):
        raise TypeError("snapshot result must be an object")
    if not all(isinstance(key, str) for key in payload):
        raise TypeError("snapshot result keys must be strings")
    unknown = set(payload) - envelope
    if unknown:
        raise ValueError(f"snapshot result contains unexpected keys: {sorted(unknown)}")
    missing = envelope - payload.keys()
    if missing:
        raise ValueError(f"snapshot result is missing keys: {sorted(missing)}")
    if isinstance(payload["schema_version"], bool) or not isinstance(
        payload["schema_version"], int
    ):
        raise TypeError("snapshot result schema_version must be an integer")
    if payload["schema_version"] != SNAPSHOT_SCHEMA_VERSION:
        raise ValueError("unsupported snapshot result schema_version")
    if not isinstance(payload["result_type"], str):
        raise TypeError("snapshot result result_type must be a string")
    if payload["result_type"] not in _SNAPSHOT_RESULT_TYPES:
        raise ValueError(f"unsupported snapshot result_type: {payload['result_type']!r}")
    for key in (
        "method",
        "evidence_status",
        "computational_status",
        "package_version",
        "provenance",
    ):
        if not isinstance(payload[key], str) or not payload[key]:
            raise TypeError(f"snapshot result {key} must be a non-empty string")
    if payload["computational_status"] != payload["evidence_status"]:
        raise ValueError("snapshot result computational_status must match evidence_status")
    for key in ("assumptions", "source_references"):
        if not isinstance(payload[key], list) or not all(
            isinstance(item, str) and item for item in payload[key]
        ):
            raise ValueError(f"snapshot result {key} must be a list of non-empty strings")
    if not isinstance(payload["artifact_versions"], Mapping) or not all(
        isinstance(key, str) and isinstance(value, str) and value
        for key, value in payload["artifact_versions"].items()
    ):
        raise ValueError("snapshot result artifact_versions must map strings to strings")
    required_versions = {"generator_catalog", "source_commit", "fixture_or_proof"}
    if set(payload["artifact_versions"]) < required_versions:
        raise ValueError("snapshot result artifact_versions are incomplete")
    if payload["literature_status"] != LiteratureStatus.NOT_ASSESSED.value:
        raise ValueError("snapshot result literature_status must be not_assessed")
    if payload["novelty_claim"] is not False:
        raise ValueError("snapshot result novelty_claim must be false")
    if payload["failure_state"] is not None:
        raise ValueError("snapshot result failure_state must be null for success")
    verification = payload["verification"]
    if not isinstance(verification, Mapping):
        raise TypeError("snapshot result verification must be an object")
    if verification.get("success") is not True or verification.get("status") != "passed":
        raise ValueError("snapshot result verification must report success")
    checks = verification.get("checks")
    if not isinstance(checks, list) or not checks:
        raise ValueError("snapshot result verification must contain checks")
    if not isinstance(payload["record"], Mapping):
        raise TypeError("snapshot result record must be an object")
    json.dumps(payload, allow_nan=False)
