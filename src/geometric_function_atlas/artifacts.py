# ── coefficient bounds ────────────────────────────────────────────────────────


def coefficient_bound(
    class_key: str, functional_key: str | None = None
) -> dict[str, Any]:
    """Look up the baked coefficient-bound catalog for one class.

    The published record preserves the sharp-versus-enclosure distinction in
    its ``sharp`` field: a sharp entry carries ``value_exact`` equal to the
    bound; an enclosure carries only the certified upper ``bound`` and slack.
    """
    _require_class(class_key)
    payload = _load_json("bounds.json")
    _check_schema(payload, "bounds.json")
    try:
        entries = payload["classes"][class_key]
    except KeyError as exc:
        available = ", ".join(sorted(payload["classes"]))
        raise UnsupportedError(
            f"class {class_key!r} has no baked bounds; available: {available}"
        ) from exc
    if functional_key is not None:
        try:
            record = entries[functional_key]
        except KeyError as exc:
            available = ", ".join(sorted(entries))
            raise UnsupportedError(
                f"class {class_key!r} has no bound for functional "
                f"{functional_key!r}; available: {available}"
            ) from exc
        return {
            "class_key": class_key,
            "functional_key": functional_key,
            "bound": record["bound"],
            "bound_float": record["bound_float"],
            "sharp": bool(record["sharp"]),
            "slack": record.get("slack"),
            "value_exact": record.get("value_exact"),
        }
    return {
        "class_key": class_key,
        "count": len(entries),
        "entries": {
            functional: {
                "bound": record["bound"],
                "bound_float": record["bound_float"],
                "sharp": bool(record["sharp"]),
                "slack": record.get("slack"),
                "value_exact": record.get("value_exact"),
            }
            for functional, record in sorted(entries.items())
        },
    }


# ── proofs gallery and detail ─────────────────────────────────────────────────


def _certificates() -> dict[str, dict[str, Any]]:
    payload = _load_json("certificates.json")
    _check_schema(payload, "certificates.json")
    return payload["certificates"]


def _proof_summary(name: str, record: Mapping[str, Any]) -> dict[str, Any]:
    sharp = record.get("sharp") or {}
    # ``sharp`` means proven sharpness. The certificate's ``exact`` flag only
    # says the candidate is an exact constant; without ``proven`` it remains a
    # certified upper enclosure. The two must stay distinct.
    return {
        "name": name,
        "class_key": record["class"],
        "functional_key": record["functional"],
        "status": record["status"],
        "bound": record.get("bound"),
        "sharp": bool(sharp.get("proven")),
        "statement": record.get("statement"),
    }


def list_proofs(
    class_key: str | None = None,
    functional_key: str | None = None,
    status: str | None = None,
    search: str | None = None,
) -> dict[str, Any]:
    """Return proof-gallery rows, optionally filtered.

    Unknown class or functional filters fail closed as unsupported; an empty
    match set is a valid result (the corpus simply has no such row).
    """
    certificates = _certificates()
    if class_key is not None:
        _require_class(class_key)
    if functional_key is not None:
        _functional_exists(functional_key)
    if status is not None:
        known = {record["status"] for record in certificates.values()}
        if status not in known:
            raise UnsupportedError(
                f"unknown proof status {status!r}; corpus statuses: {sorted(known)}"
            )
    rows = []
    for name, record in sorted(certificates.items()):
        if class_key is not None and record["class"] != class_key:
            continue
        if functional_key is not None and record["functional"] != functional_key:
            continue
        if status is not None and record["status"] != status:
            continue
        if search is not None:
            needle = search.lower()
            haystack = f"{name} {record.get('statement', '')}".lower()
            if needle not in haystack:
                continue
        rows.append(_proof_summary(name, record))
    return {"count": len(rows), "rows": rows}


def _functional_exists(functional_key: str) -> None:
    certificates = _certificates()
    known = {record["functional"] for record in certificates.values()}
    if functional_key not in known:
        raise UnsupportedError(
            f"unknown functional {functional_key!r}; corpus functionals: "
            f"{sorted(known)}"
        )


def get_proof(name: str, *, raw: bool = False) -> dict[str, Any]:
    """Return one proof certificate's detail record, or the raw record."""
    certificates = _certificates()
    try:
        record = certificates[name]
    except KeyError as exc:
        raise UnsupportedError(
            f"unknown proof {name!r}; use 'gfa proofs' to list certificate names"
        ) from exc
    from .schur import functional_display  # local import avoids a cycle at load

    sharp = record.get("sharp") or {}
    candidate = sharp.get("candidate") or {}
    class_record = _require_class(record["class"])
    display = functional_display(record["functional"])
    detail = {
        "name": name,
        "class_key": record["class"],
        "class_name": class_record["name"],
        "functional_key": record["functional"],
        "functional_display": display[0],
        "functional_latex": display[1],
        "status": record["status"],
        "statement": record.get("statement"),
        "bound": record.get("bound"),
        "slack": record.get("slack"),
        "engine": record.get("engine"),
        "evaluator": (record.get("evaluator") or {}).get("definition"),
        "method_label": f"{record.get('engine')} / "
        f"{(record.get('evaluator') or {}).get('type', 'unknown')}",
        "lemmas": list(record.get("lemmas") or []),
        "n_leaves": record.get("n_leaves"),
        "n_leaves_parts": record.get("n_leaves_parts"),
        "leaves_npz": record.get("leaves_npz"),
        "sharp": {
            "proven": bool(sharp.get("proven")),
            "exact": bool(sharp.get("exact")),
            "bracket_lo": sharp.get("bracket_lo"),
            "bracket_hi": sharp.get("bracket_hi"),
            "candidate_exact": candidate.get("value_exact"),
            "candidate_float": candidate.get("value_float"),
            "candidate_method": candidate.get("method"),
            "extremal_gammas": list(sharp.get("extremal_gammas") or []),
            "extremal_omega": sharp.get("extremal_omega"),
            "method": sharp.get("method"),
            "note": sharp.get("note"),
            "reference": sharp.get("reference"),
        },
    }
    if raw:
        detail["certificate"] = dict(record)
    return detail


# ── open problems ─────────────────────────────────────────────────────────────


def open_problems(kind: str = "all") -> dict[str, Any]:
    """Return open-problem rows, preserving the two published categories.

    ``enclosure`` rows are certified brackets awaiting sharp closure;
    ``numerical`` rows are uncertified numerical conjectures. The two are never
    merged, and neither is presented as a proved sharp value.
    """
    if kind not in {"all", "enclosure", "numerical"}:
        raise InvalidInputError(
            "kind must be one of: all, enclosure, numerical"
        )
    payload = _load_json("open_problems.json")
    _check_schema(payload, "open_problems.json")
    enclosures = [dict(row) for row in payload["enclosures"]]
    conjectures = [dict(row) for row in payload["conjectures"]]
    counts = {"enclosures": len(enclosures), "numerical": len(conjectures)}
    record: dict[str, Any] = {"counts": counts}
    if kind in {"all", "enclosure"}:
        record["enclosures"] = enclosures
    if kind in {"all", "numerical"}:
        record["conjectures"] = conjectures
    return record


# ── reconciliation rows ───────────────────────────────────────────────────────


def _category_tokens(category: str) -> set[str]:
    """Split a reconciliation bucket into its letters.

    Rows may carry compound buckets such as ``"A+C*"`` (a row that falls under
    both the A and C summaries); each token is a single A–D letter.
    """
    return {token.rstrip("*") for token in category.split("+")}


def reconciliation(
    class_key: str | None = None,
    functional_key: str | None = None,
    category: str | None = None,
) -> dict[str, Any]:
    """Return literature-reconciliation counts and rows.

    ``counts`` are the published A–D summary buckets; ``rows`` may carry
    compound buckets (for example ``"A+C*"``). ``category`` filters rows whose
    bucket includes the given letter. No-match rows are literature findings,
    never novelty certificates.
    """
    payload = _load_json("reconciliation.json")
    _check_schema(payload, "reconciliation.json")
    counts = dict(payload["counts"])
    rows = [dict(row) for row in payload["rows"]]
    if category is not None:
        normalized = category.upper()
        if normalized not in counts:
            raise InvalidInputError(
                f"unknown reconciliation category {category!r}; categories: "
                f"{sorted(counts)}"
            )
    if class_key is not None:
        _require_class(class_key)
    if functional_key is not None:
        _functional_exists(functional_key)
    filtered = [
        row
        for row in rows
        if (class_key is None or row["class_key"] == class_key)
        and (functional_key is None or row["functional_key"] == functional_key)
        and (
            category is None
            or category.upper() in _category_tokens(row["category"])
        )
    ]
    return {"counts": counts, "total": len(rows), "rows": filtered}


