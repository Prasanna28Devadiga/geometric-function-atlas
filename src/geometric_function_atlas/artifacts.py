_GAMMA_STRING = re.compile(r"^[+-]?[0-9]+(?:/[0-9]+)?$", re.ASCII)


def _data_file(name: str) -> Any:
    """Return the packaged resource handle for one baked artifact."""
    return resources.files("geometric_function_atlas").joinpath("data", name)


@cache
def _load_json(name: str) -> dict[str, Any]:
    """Load one baked JSON artifact, failing closed on absence or corruption."""
    try:
        text = _data_file(name).read_text(encoding="utf-8")
    except (FileNotFoundError, IsADirectoryError, OSError) as exc:
        raise CorruptArtifactError(
            f"baked artifact {name} is missing from the package data"
        ) from exc
    try:
        payload = json.loads(text)
    except json.JSONDecodeError as exc:
        raise CorruptArtifactError(f"baked artifact {name} is not valid JSON") from exc
    if not isinstance(payload, dict):
        raise CorruptArtifactError(f"baked artifact {name} is not a JSON object")
    return payload


@cache
def _load_text(name: str) -> str:
    try:
        return _data_file(name).read_text(encoding="utf-8")
    except (FileNotFoundError, IsADirectoryError, OSError) as exc:
        raise CorruptArtifactError(
            f"baked artifact {name} is missing from the package data"
        ) from exc


def _sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _check_schema(payload: Mapping[str, Any], name: str) -> None:
    version = payload.get("schema_version")
    if not isinstance(version, int) or isinstance(version, bool):
        raise CorruptArtifactError(
            f"baked artifact {name} carries no integer schema_version"
        )
    if version != SNAPSHOT_SCHEMA_VERSION:
        raise CorruptArtifactError(
            f"baked artifact {name} uses schema_version {version}, "
            f"expected {SNAPSHOT_SCHEMA_VERSION}"
        )


def _manifest() -> dict[str, Any]:
    manifest = _load_json("manifest.json")
    _check_schema(manifest, "manifest.json")
    return manifest


def _classes_payload() -> dict[str, Any]:
    payload = _load_json("classes.json")
    _check_schema(payload, "classes.json")
    return payload["classes"]


def _require_class(class_key: str) -> dict[str, Any]:
    classes = _classes_payload()
    try:
        return classes[class_key]
    except KeyError as exc:
        available = ", ".join(sorted(classes))
        raise UnsupportedError(
            f"unknown class {class_key!r}; available classes: {available}"
        ) from exc


def _normalize_gamma(value: Any) -> Any:
    """Return a replay-safe exact Schur parameter from a certificate record.

    The baked certificates store integer strings (``"0"``), integer values, and
    exactly-representable float zeros/ones (``0.0``, ``1.0``). Floats that are
    not exactly integer-valued cannot be replayed exactly and fail closed.
    """
    if isinstance(value, bool):
        raise UnresolvedError("certificate extremal gamma is a bool")
    if isinstance(value, float):
        if value.is_integer():
            return int(value)
        raise UnresolvedError(
            f"certificate extremal gamma {value!r} is not exactly representable"
        )
    if isinstance(value, int):
        return value
    if isinstance(value, str):
        if _GAMMA_STRING.fullmatch(value) is None:
            raise UnresolvedError(
                f"certificate extremal gamma {value!r} is not an exact rational"
            )
        return value
    raise UnresolvedError(
        f"certificate extremal gamma has unsupported type {type(value).__name__}"
    )


def _exact_or_float(record: Mapping[str, Any], key: str) -> sp.Expr | float | None:
    """Parse an exact string field, falling back to its float sibling."""
    value = record.get(key)
    if isinstance(value, str):
        try:
            return parse_exact_expression(value)
        except ExactExpressionError:
            pass
    sibling = record.get(f"{key}_float")
    if isinstance(sibling, (int, float)):
        return float(sibling)
    return None


# ── snapshot integrity ────────────────────────────────────────────────────────


def snapshot_info() -> dict[str, Any]:
    """Return the snapshot identity record (version, date, source, files)."""
    manifest = _manifest()
    files = dict(sorted(manifest["files"].items()))
    return {
        "artifact_version": manifest["artifact_version"],
        "snapshot_date": manifest["snapshot_date"],
        "source_repo": manifest["source_repo"],
        "source_commit": manifest["source_commit"],
        "schema_version": manifest["schema_version"],
        "recipe": manifest["recipe"],
        "files": {
            name: {
                "sha256": entry["sha256"],
                "schema_version": entry.get("schema_version"),
            }
            for name, entry in files.items()
        },
    }


def snapshot_verify() -> dict[str, Any]:
    """Verify every baked artifact against the shipped manifest checksums.

    Any missing file, checksum mismatch, or schema-version mismatch raises
    :class:`CorruptArtifactError`; a passing call returns the integrity record.
    """
    manifest = _manifest()
    checks: list[VerificationCheck] = []
    for name in sorted(manifest["files"]):
        entry = manifest["files"][name]
        resource = _data_file(name)
        try:
            observed = _sha256_bytes(resource.read_bytes())
        except (FileNotFoundError, IsADirectoryError, OSError) as exc:
            raise CorruptArtifactError(
                f"baked artifact {name} is missing from the package data"
            ) from exc
        ok = observed == entry["sha256"]
        checks.append(
            VerificationCheck(
                name=f"artifact_checksum_{name}",
                checked=f"SHA-256 of data/{name}",
                expected=entry["sha256"],
                observed=observed,
                status=CheckStatus.PASS if ok else CheckStatus.FAIL,
                scope="shipped snapshot integrity",
                failure_reason=None if ok else "checksum mismatch",
            )
        )
        if ok and name.endswith(".json"):
            payload = json.loads(resource.read_text(encoding="utf-8"))
            version = payload.get("schema_version")
            schema_ok = isinstance(version, int) and not isinstance(version, bool) and (
                version == SNAPSHOT_SCHEMA_VERSION
            )
            checks.append(
                VerificationCheck(
                    name=f"artifact_schema_{name}",
                    checked=f"schema_version of data/{name}",
                    expected=SNAPSHOT_SCHEMA_VERSION,
                    observed=version,
                    status=CheckStatus.PASS if schema_ok else CheckStatus.FAIL,
                    scope="shipped snapshot integrity",
                    failure_reason=None if schema_ok else "schema version mismatch",
                )
            )
    report = VerificationReport(tuple(checks))
    if not report.success:
        failed = [check for check in checks if check.status is CheckStatus.FAIL]
        detail = "; ".join(f"{check.name}: {check.failure_reason}" for check in failed)
        raise CorruptArtifactError(f"snapshot verification failed: {detail}")
    return {
        "artifact_version": manifest["artifact_version"],
        "snapshot_date": manifest["snapshot_date"],
        "source_commit": manifest["source_commit"],
        "files_verified": len(manifest["files"]),
        "checks": report.to_dict(),
    }


